export const ALL_EMOJI: EmojiEntry[] = EMOJI_CATEGORIES.flatMap(
  (category) => category.emojis,
);

/** Remove acento para a busca casar "coracao" com "coração". */
const fold = (value: string) =>
  value
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");

export function searchEmoji(query: string, limit = 90) {
  const needle = fold(query.trim());
  if (!needle) return [];
  const starts: EmojiEntry[] = [];
  const contains: EmojiEntry[] = [];
  // Um mesmo caractere pode estar em duas categorias (🔥 é natureza e é
  // símbolo). Na busca ele precisa aparecer uma vez só.
  const seen = new Set<string>();
  for (const item of ALL_EMOJI) {
    if (seen.has(item.char)) continue;
    const haystack = fold(item.keywords);
    if (haystack.startsWith(needle) || fold(item.name).startsWith(needle)) {
      starts.push(item);
      seen.add(item.char);
    } else if (haystack.includes(needle)) {
      contains.push(item);
      seen.add(item.char);
    }
    if (starts.length >= limit) break;
  }
  return [...starts, ...contains].slice(0, limit);
}
