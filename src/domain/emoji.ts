/**
 * Conjunto Unicode padrão, agrupado como no seletor do Discord.
 *
 * É um recorte curado, não a tabela Unicode inteira: carregar as ~3800
 * sequências custaria mais de um megabyte de bundle para um app que roda
 * offline, e a cauda longa quase nunca é usada. As palavras-chave estão em
 * português porque a busca é feita em português.
 */
export interface EmojiEntry {
  /** O caractere em si. */
  char: string;
  /** Nome curto, usado como `:atalho:` e no rodapé do seletor. */
  name: string;
  /** Termos de busca, separados por espaço. */
  keywords: string;
}

export interface EmojiCategory {
  id: string;
  label: string;
  icon: string;
  emojis: EmojiEntry[];
}

const entry = (char: string, name: string, keywords = ""): EmojiEntry => ({
  char,
  name,
  keywords: `${name} ${keywords}`.trim(),
});

